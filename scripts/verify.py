def load_port_map(data):
    if hashlib.sha256(data).hexdigest() != MC_PORT_MAP_SHA256:
        raise ValueError("MC port map differs from the reviewed map")
    record = json.loads(data)
    if record["count"] != MC_PORT_COUNT or len(record["theorems"]) != MC_PORT_COUNT:
        raise ValueError("MC port map does not cover the reviewed promised theorems")
    for name, entry in record["theorems"].items():
        same = entry["accepted_type"] == entry["current_type"]
        if (entry["classification"] == "identical") != same or (
                not same and entry["classification"] not in MC_PORT_CLASSES):
            raise ValueError(f"MC port map entry inconsistent with its class: {name}")
    return record["theorems"]


def port_map():
    global _PORT_MAP
    if _PORT_MAP is None:
        _PORT_MAP = load_port_map((ROOT / MC_PORT_MAP).read_bytes())
    return _PORT_MAP


def same_or_ported_type(name, before, after, mapping=None):
    if before == after:
        return True
    entry = (port_map() if mapping is None else mapping).get(name)
    return (entry is not None and entry["classification"] in MC_PORT_CLASSES
            and entry["accepted_type"] == before and entry["current_type"] == after)


IMPORT_LINE = re.compile(rb"import[ \t]+\S+[ \t]*\r?\n?")


def strip_imports(data):
    """Remove the Lean `import` header: the leading run of lines of the form `import <Module>`. Every later line,
    including any later line starting with `import`, is kept, so it still counts as a change."""
    lines = data.splitlines(keepends=True)
    start = 0
    while start < len(lines) and IMPORT_LINE.fullmatch(lines[start]):
        start += 1
    return b"".join(lines[start:])


def load_mr_paths(data):
    """The pinned MR-1 path map as {old path: new path}."""
    if hashlib.sha256(data).hexdigest() != MR_PATHS_SHA256:
        raise ValueError("MR path map differs from the reviewed map")
    entries = json.loads(data)
    if not isinstance(entries, list) or not entries:
        raise ValueError("MR path map is not a non-empty list")
    moves = {}
    for entry in entries:
        if (not isinstance(entry, dict) or set(entry) != {"old_path", "new_path"}
                or not all(isinstance(entry[k], str) and entry[k].startswith("CFDLean/") and entry[k].endswith(".lean")
                           for k in entry)):
            raise ValueError(f"Malformed MR path map entry: {entry}")
        if entry["old_path"] in moves:
            raise ValueError(f"MR path map lists a file twice: {entry['old_path']}")
        moves[entry["old_path"]] = entry["new_path"]
    if len(set(moves.values())) != len(moves):
        raise ValueError("MR path map sends two files to one path")
    if set(moves.values()) & (set(moves) - {old for old, new in moves.items() if old == new}):
        raise ValueError("MR path map moves a file onto another moved file's old path")
    return moves


def mr_paths():
    global _MR_PATHS
    if _MR_PATHS is None:
        _MR_PATHS = load_mr_paths((ROOT / MR_PATHS).read_bytes())
    return _MR_PATHS


