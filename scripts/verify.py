def same_or_ported_source(path, accepted_sha256, moves=None, read=read_source, blob=None,
                          accepted_revision=ACCEPTED_BASELINE):
    """An accepted source (old `path`) is unchanged, or byte-identical to the MC-T port. A file listed in the MR-1 map
    is read at its new path and must equal, after removing the `import` header of both, the accepted bytes (the blob
    of `accepted_revision` whose sha256 is the accepted one) or the MC-T port bytes."""
    moves = mr_paths() if moves is None else moves
    blob = git_blob if blob is None else blob

    def reference(revision):
        try:
            return blob(revision, path)
        except subprocess.CalledProcessError:
            return None
    try:
        data = read(moves.get(path, path))
    except (OSError, KeyError):
        return False
    if path not in moves:
        return hashlib.sha256(data).hexdigest() == accepted_sha256 or data == reference(MC_PORT_REVISION)
    data = strip_imports(data)
    accepted = reference(accepted_revision)
    references = [reference(MC_PORT_REVISION)]
    if accepted is not None and hashlib.sha256(accepted).hexdigest() == accepted_sha256:
        references.append(accepted)
    return any(ref is not None and strip_imports(ref) == data for ref in references)


def check_mr_sources(moves, read, base, exists):
    """MR-1 changed only paths and `import` lines: every mapped file equals its pre-MR-1 bytes (MR_BASE_REVISION) up to
    the `import` header, a moved file's old path is gone, and the removed umbrella is gone."""
    for old, new in sorted(moves.items()):
        try:
            before = base(old)
        except subprocess.CalledProcessError:
            raise ValueError(f"MR path map names a file absent before MR-1: {old}")
        if not exists(new) or (old != new and exists(old)):
            raise ValueError(f"MR-1 move not carried out: {old} -> {new}")
        if strip_imports(read(new)) != strip_imports(before):
            raise ValueError(f"MR-1 changed more than import lines: {new}")
    for path in MR_REMOVED:
        if exists(path):
            raise ValueError(f"MR-1 removed file still present: {path}")
    return len(moves)


