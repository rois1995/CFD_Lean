def check_mc_n(rows, record, other_promised, spec_text):
    results = record["results"]
    ids = [r["id"] for r in results]
    names = [r["theorem"] for r in results]
    if (len(results) != MC_N_COUNT or len(set(ids)) != len(ids) or len(set(names)) != len(names)
            or any(not i.startswith("MC-N.") for i in ids)):
        raise ValueError("MC-N result bindings differ from the frozen scope")
    for module, name in MC_N_MODULES.items():
        if f"`{name}`" not in spec_text:
            raise ValueError(f"MC-N module not in the frozen module list: {module}")
    for result in results:
        name = result["theorem"]
        if result["module"] not in MC_N_MODULES or not name.startswith("CFDLean.Num."):
            raise ValueError(f"MC-N theorem outside the numerical core: {name}")
        row = rows.get(name)
        if (row is None or row["kind"] != "theorem" or not row["root"] or row["unsafe"]
                or set(row["axioms"]) - ALLOWED):
            raise ValueError(f"Missing MC-N theorem: {name}")
        if row["module"] != result["module"]:
            raise ValueError(f"MC-N theorem outside its module: {name}")
    if set(names) & set(other_promised):
        raise ValueError("MC-N rebinds an M1-M5 promised theorem")
    return sorted(names)


def check_mc_n_sources(paths, read, base, moves=None):
    """Pre-existing CFDLean sources (M1-M5) are byte-identical to the MC-N base; only the umbrella changes. A file
    listed in the MR-1 map is compared at its old path, without the `import` header."""
    moves = {} if moves is None else moves
    origin = {new: old for old, new in moves.items()}
    checked = 0
    for path in paths:
        old = origin.get(path, path)
        if path == "CFDLean.lean" or old.startswith("CFDLean/Num/") or old == "CFDLean/Num.lean":
            continue
        try:
            before = base(old)
        except subprocess.CalledProcessError:
            continue
        same = (strip_imports(read(path)) == strip_imports(before)) if path in origin else read(path) == before
        if not same:
            raise ValueError(f"MC-N changed an M1-M5 source: {path}")
        checked += 1
    if not checked:
        raise ValueError("No M1-M5 source compared with the MC-N base")
    return checked


def m1_accepted_theorems(integrity_text):
    """M1 has no result map: its accepted theorems are the `#print axioms` list of Integrity.lean (hash-pinned)."""
    names = re.findall(r"^#print axioms (\S+)$", integrity_text, re.MULTILINE)
    if not names or len(set(names)) != len(names):
        raise ValueError("M1 accepted theorem list missing or duplicated in Integrity.lean")
    return {"CFDLean." + name: ("M1", None) for name in names}


def catalog_index(milestone, contract):
    """Promised theorem name -> (milestone, result ID) from a result map (M2-M5 `declarations`, MC-N `theorem`)."""
    index = {}
    for result in contract["results"]:
        names = [result["theorem"]] if "theorem" in result else [
            name for part in result.get("parts", [result]) for name in part["declarations"]]
        for name in names:
            if name in index:
                raise ValueError(f"Promised theorem bound twice: {name}")
            index[name] = (milestone, result["id"])
    return index


def check_catalog(record, expected, rows):
    """The catalog covers exactly the expected promised theorems, with valid IDs, modules, layers, tags and status."""
    entries = record["theorems"]
    names = [entry.get("name") for entry in entries]
    if len(set(names)) != len(names) or set(names) != set(expected):
        raise ValueError("Catalog does not cover exactly the promised theorems")
    for entry in entries:
        name = entry["name"]
        milestone, result_id = expected[name]
        if set(entry) != set(CATALOG_FIELDS) or any(
                not isinstance(entry[field], str) or not entry[field].strip()
                for field in CATALOG_FIELDS if field != "methods"):
            raise ValueError(f"Malformed catalog entry: {name}")
        if entry["milestone"] != milestone or entry["status"] != CATALOG_STATUS[milestone]:
            raise ValueError(f"Catalog milestone or status wrong: {name}")
        if entry["id"] != result_id if result_id is not None else not entry["id"].startswith("M1-"):
            raise ValueError(f"Catalog result ID wrong: {name}")
        if entry["layer"] not in CATALOG_LAYERS or entry["methods"] not in CATALOG_METHODS:
            raise ValueError(f"Catalog layer or method tag invalid: {name}")
        row = rows.get(name)
        if row is None or row["kind"] != "theorem" or not row["root"] or row["module"] != entry["module"]:
            raise ValueError(f"Catalog theorem missing or outside its module: {name}")
    return len(entries)


