def load_jst1_frozen(data):
    """The pinned JST1 frozen list as {path: sha256}; every listed path is a Lean file of the paper or of the core."""
    if hashlib.sha256(data).hexdigest() != JST1_FROZEN_SHA256:
        raise ValueError("JST1 frozen hash list differs from the pinned list")
    entries = {}
    for line in data.decode().splitlines():
        match = re.fullmatch(r"([0-9a-f]{64})  (CFDLean/\S+\.lean)", line)
        if match is None or match.group(2) in entries:
            raise ValueError(f"Malformed JST1 frozen hash line: {line!r}")
        entries[match.group(2)] = match.group(1)
    if not entries:
        raise ValueError("Empty JST1 frozen hash list")
    return entries


def check_jst1_frozen(entries, read, paths):
    """Every frozen file has its hash, and every JST1 statement or definition file (all of CFDLean/Papers/JST1 except
    Proofs/) is frozen."""
    for path, digest in sorted(entries.items()):
        try:
            data = read(path)
        except (OSError, KeyError):
            raise ValueError(f"JST1 frozen file missing: {path}")
        if hashlib.sha256(data).hexdigest() != digest:
            raise ValueError(f"JST1 frozen file changed: {path}")
    unfrozen = [path for path in paths if path.startswith(JST1_ROOT) and not path.startswith(JST1_ROOT + "Proofs/")
                and path not in entries]
    if unfrozen:
        raise ValueError(f"JST1 statement or definition file not frozen: {unfrozen[0]}")
    return len(entries)


def jst1_frozen_ids(spec_texts):
    """The frozen JST1 result IDs: one per statement definition of the pinned statement files."""
    ids = [f"{a}-{b}.{c}" for text in spec_texts for a, b, c in JST1_SPEC_DEF.findall(text)]
    if len(ids) != JST1_COUNT or len(set(ids)) != len(ids):
        raise ValueError("JST1 statement files do not define the frozen statements")
    return set(ids)


def strip_lean_comments(text):
    """Lean source without `--` line comments and (nested) `/- -/` block comments; string literals are kept."""
    out, i, depth, n = [], 0, 0, len(text)
    while i < n:
        if depth:
            if text.startswith("/-", i):
                depth, i = depth + 1, i + 2
            elif text.startswith("-/", i):
                depth, i = depth - 1, i + 2
            else:
                i += 1
        elif text.startswith("/-", i):
            depth, i = 1, i + 2
        elif text.startswith("--", i):
            while i < n and text[i] != "\n":
                i += 1
        elif text[i] == '"':
            j = i + 1
            while j < n and text[j] != '"':
                j += 2 if text[j] == "\\" else 1
            out.append(text[i:j + 1])
            i = j + 1
        else:
            out.append(text[i])
            i += 1
    return "".join(out)


def check_jst1(rows, records, audit_text, core_theorems, frozen_ids):
    """The 119 JST1 bindings: exactly the frozen IDs, each in the result map of its paper part and bound to the
    statement of its ID; unique names in CFDLean.JST1; each bound in the audit (outside comments); each a root theorem
    with standard axioms in its module whose type is its statement; the statement a definition; and a delegated
    binding uses its MC-N theorem."""
    if len(records) != len(JST1_RESULTS):
        raise ValueError("JST1 result bindings differ from the frozen scope")
    bindings = [(paper, result_id, binding) for paper, record in zip(JST1_PAPERS, records)
                for result_id, binding in record["bindings"].items()]
    ids = [result_id for _, result_id, _ in bindings]
    names = [binding["theorem"] for _, _, binding in bindings]
    if (len(bindings) != JST1_COUNT or len(set(ids)) != len(ids) or len(set(names)) != len(names)
            or set(ids) != set(frozen_ids) or any(not JST1_ID.fullmatch(result_id) for result_id in ids)):
        raise ValueError("JST1 result bindings differ from the frozen scope")
    for paper, result_id, binding in bindings:
        if (not result_id.startswith(paper + "-")
                or binding["statement"] != "CFDLean.JST1.Spec." + result_id.replace("-", "_").replace(".", "_")):
            raise ValueError(f"JST1 result ID bound to another statement or paper part: {result_id}")
    bindings = [(result_id, binding) for _, result_id, binding in bindings]
    bound = set(re.findall(r"^example : (\S+) := (\S+)$", strip_lean_comments(audit_text), re.MULTILINE))
    delegated = []
    for result_id, binding in bindings:
        statement, name = binding["statement"], binding["theorem"]
        if not statement.startswith("CFDLean.JST1.Spec.") or not name.startswith("CFDLean.JST1.Proofs."):
            raise ValueError(f"JST1 binding outside the paper namespace: {result_id}")
        if (statement, name) not in bound:
            raise ValueError(f"JST1 binding not in the kernel audit: {result_id}")
        row = rows.get(name)
        if (row is None or row["kind"] != "theorem" or not row["root"] or row["unsafe"]
                or set(row["axioms"]) - ALLOWED):
            raise ValueError(f"Missing JST1 theorem: {name}")
        if row["module"] != binding["module"] or binding["file"] != binding["module"].replace(".", "/") + ".lean":
            raise ValueError(f"JST1 theorem outside its module: {name}")
        if row["type"] != statement:
            raise ValueError(f"JST1 theorem does not state its statement: {name}")
        if rows.get(statement, {}).get("kind") != "definition":
            raise ValueError(f"JST1 statement is not a definition: {statement}")
        core = binding.get("core_theorem")
        if core is not None:
            if core not in core_theorems or core not in row["direct"]:
                raise ValueError(f"JST1 delegation does not use its MC-N theorem: {name}")
            delegated.append(name)
    return sorted(names), sorted(delegated)


def check_jst1_comparator(rows, records, read=read_source):
    """The JST1 comparator files: the pinned challenge imports only JST1 statement modules and states each frozen
    statement under the name of a solution theorem; the configuration names exactly those theorems; each solution
    theorem is a root theorem with standard axioms whose type is its statement and which uses its JST1 proof."""
    challenge = read(JST1_CHALLENGE)
    if hashlib.sha256(challenge).hexdigest() != JST1_CHALLENGE_SHA256:
        raise ValueError("JST1 comparator challenge changed")
    imports = imported_modules(challenge)
    if not imports or any(not module.startswith("CFDLean.Papers.JST1.Spec.") for module in imports):
        raise ValueError("JST1 comparator challenge imports a module outside the JST1 statements")
    config = json.loads(read(JST1_COMPARATOR))
    bindings = [binding for record in records for binding in record["bindings"].values()]
    names = [f"{JST1_SOLUTION}.{binding['theorem'].rsplit('.', 1)[1]}" for binding in bindings]
    if (config.get("challenge_module") != "Challenges.JST1" or config.get("solution_module") != JST1_SOLUTION
            or config.get("theorem_names") != names or config.get("definition_names") != []
            or set(config.get("permitted_axioms", [])) != ALLOWED):
        raise ValueError("JST1 comparator configuration differs from the result maps")
    stated = set(re.findall(r"^theorem (\S+) : (\S+) := sorry$", challenge.decode(), re.MULTILINE))
    for name, binding in zip(names, bindings):
        if (name.rsplit(".", 1)[1], binding["statement"]) not in stated:
            raise ValueError(f"JST1 statement not in the comparator challenge: {binding['statement']}")
        row = rows.get(name)
        if (row is None or row["kind"] != "theorem" or not row["root"] or row["unsafe"]
                or set(row["axioms"]) - ALLOWED or row["module"] != JST1_SOLUTION
                or row["type"] != binding["statement"] or binding["theorem"] not in row["direct"]):
            raise ValueError(f"JST1 comparator solution theorem wrong: {name}")
    if len(stated) != len(names):
        raise ValueError("JST1 comparator challenge states extra theorems")
    return len(names)


def check_forbidden_tokens(paths, read):
    """No forbidden token (sorry, admit, axiom declarations, native_decide, implemented_by, extern, opaque, unsafe) in
    the paper sources."""
    for path in paths:
        match = FORBIDDEN.search(read(path).decode())
        if match:
            raise ValueError(f"Forbidden token {match.group(0).strip()!r} in {path}")
    if not paths:
        raise ValueError("No source scanned for forbidden tokens")
    return len(paths)


