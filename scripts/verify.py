# MR-3: one table-driven check of the accepted (inherited) bindings and types of M2, M3 and M4. Each row gives the
# milestone's stage order, whether its results are split into parts (M3), whether the current stage may not roll back
# below the accepted one (M4), whether the accepted stages are all filtered before the first binding is checked (M2),
# and the failure messages of the former per-milestone functions, so the behaviour (accepted revisions, checked
# bindings, comparisons, failures and their order, also on malformed input) is the same. M2 keeps its stages in a list
# as before (the message of a failed `index` differs between list and tuple). M5 is not accepted and has no row.
INHERITED = {
    "M2": {"stages": ["M2a", "M2b", "M2c", "M2d"], "parts": False, "no_rollback": False, "filter_first": True,
           "binding_error": "Accepted {id} binding or stage changed", "type_error": "Accepted theorem type changed: {name}"},
    "M3": {"stages": ("M3a", "M3b"), "parts": True, "no_rollback": False, "filter_first": False,
           "binding_error": "Accepted {id} part/bindings changed", "type_error": "Accepted M3 type changed: {name}"},
    "M4": {"stages": ("M4a", "M4b"), "parts": False, "no_rollback": True, "filter_first": False,
           "binding_error": "Accepted {id} binding/stage changed", "type_error": "Accepted M4 type changed: {name}"},
}


def check_inherited_milestone(milestone, rows, contract, accepted, evidence):
    """Every binding of `accepted` up to its current stage is unchanged in `contract`, has declarations, and each
    declaration keeps its accepted type (or its MC-T port type). Returns {name: {accepted_type, current_type}}.
    Fields are read in the order of the former per-milestone functions (M2: accepted stages filtered before the
    current bindings are indexed; result IDs read only when needed), so malformed input fails the same way."""
    spec = INHERITED[milestone]
    stages = spec["stages"]
    if spec["no_rollback"] and stages.index(contract["current_stage"]) < stages.index(accepted["current_stage"]):
        raise ValueError(f"Accepted {milestone} current stage rolled back")

    def units(record):
        for result in record["results"]:
            for unit in (result["parts"] if spec["parts"] else [result]):
                yield result, unit

    def key(result, unit):
        return (result["id"], unit["stage"]) if spec["parts"] else result["id"]

    def active(unit):
        return stages.index(unit["stage"]) <= stages.index(accepted["current_stage"])

    if spec["filter_first"]:
        accepted_units = [(result, unit) for result, unit in units(accepted) if active(unit)]
    current = {key(result, unit): unit for result, unit in units(contract)}
    comparisons = {}
    for result, unit in (accepted_units if spec["filter_first"] else units(accepted)):
        if not spec["filter_first"] and not active(unit):
            continue
        if not unit["declarations"] or current.get(key(result, unit)) != unit:
            raise ValueError(spec["binding_error"].format(id=result["id"]))
        for name in unit["declarations"]:
            before, after = evidence["declarations"][name]["type"], rows[name]["type"]
            if not same_or_ported_type(name, before, after):
                raise ValueError(spec["type_error"].format(name=name))
            comparisons[name] = {"accepted_type": before, "current_type": after}
    return comparisons


def check_inherited(rows, contract, accepted_contract, accepted_evidence):
    return check_inherited_milestone("M2", rows, contract, accepted_contract, accepted_evidence)


def check_m3_inherited(rows, contract, accepted, evidence):
    return check_inherited_milestone("M3", rows, contract, accepted, evidence)


def check_m4_inherited(rows, contract, accepted, evidence):
    return check_inherited_milestone("M4", rows, contract, accepted, evidence)


def check_mc_n(rows, record, other_promised, spec_text):
    results = record["results"]
    ids = [r["id"] for r in results]
    names = [r["theorem"] for r in results]
    if (len(results) != MC_N_COUNT or len(set(ids)) != len(ids) or len(set(names)) != len(names)
            or any(not i.startswith("MC-N.") for i in ids)):
        raise ValueError("MC-N result bindings differ from the frozen scope")
    for module, name in MC_N_MODULES.items():
        if f"`{name}`" not in spec_text:
            raise ValueError(f"MC-N module not in the frozen module list: {module}")
    for result in results:
        name = result["theorem"]
        if result["module"] not in MC_N_MODULES or not name.startswith("CFDLean.Num."):
            raise ValueError(f"MC-N theorem outside the numerical core: {name}")
        row = rows.get(name)
        if (row is None or row["kind"] != "theorem" or not row["root"] or row["unsafe"]
                or set(row["axioms"]) - ALLOWED):
            raise ValueError(f"Missing MC-N theorem: {name}")
        if row["module"] != result["module"]:
            raise ValueError(f"MC-N theorem outside its module: {name}")
    if set(names) & set(other_promised):
        raise ValueError("MC-N rebinds an M1-M5 promised theorem")
    return sorted(names)


def check_mc_n_sources(paths, read, base, moves=None):
    """Pre-existing CFDLean sources (M1-M5) are byte-identical to the MC-N base; only the umbrella changes. A file
    listed in the MR-1 map is compared at its old path, without the `import` header."""
    moves = {} if moves is None else moves
    origin = {new: old for old, new in moves.items()}
    checked = 0
    for path in paths:
        old = origin.get(path, path)
        if path == "CFDLean.lean" or old.startswith("CFDLean/Num/") or old == "CFDLean/Num.lean":
            continue
        try:
            before = base(old)
        except subprocess.CalledProcessError:
            continue
        same = (strip_imports(read(path)) == strip_imports(before)) if path in origin else read(path) == before
        if not same:
            raise ValueError(f"MC-N changed an M1-M5 source: {path}")
        checked += 1
    if not checked:
        raise ValueError("No M1-M5 source compared with the MC-N base")
    return checked


def imported_modules(data):
    """Every module named by an `import` line of a Lean source, wherever the line is."""
    return re.findall(r"^[ \t]*(?:public[ \t]+)?import[ \t]+(\S+)", data.decode(), re.MULTILINE)


def check_burgers(milestone, rows, record, contract_text, read=read_source, pins=None):
    """One Burgers milestone: the result map covers exactly the frozen IDs; each bound definition and theorem is in its
    module, each theorem is a root theorem with standard axioms; the trusted statements and the comparator challenge
    are the pinned files and import only Mathlib and the hash-pinned `trusted_inputs` of the milestone (the code under
    verification, if any); each bridge theorem states its trusted statement and uses a promised theorem of its
    result ID."""
    pins = BURGERS[milestone] if pins is None else pins
    check_result_ids(record, contract_text, milestone)
    modules = record["modules"]

    def theorem(name, module):
        row = rows.get(name)
        if (row is None or row["kind"] != "theorem" or not row["root"] or row["unsafe"]
                or set(row["axioms"]) - ALLOWED or row["module"] != module):
            raise ValueError(f"Missing {milestone} theorem: {name}")
        return row

    def definition(name, module):
        row = rows.get(name)
        if row is None or row["kind"] not in ("definition", "inductive") or row["module"] != module:
            raise ValueError(f"Missing {milestone} definition: {name}")

    bound = [name for result in record["results"]
             for field in ("definitions", "supporting", "declarations") for name in result[field]]
    if len(set(bound)) != len(bound) or set(bound) != set(modules):
        raise ValueError(f"{milestone} bindings and module map disagree")
    promised = {}
    for result in record["results"]:
        if not result["definitions"] and not result["declarations"]:
            raise ValueError(f"{milestone} result without a binding: {result['id']}")
        for name in result["definitions"]:
            definition(name, modules[name])
        for name in result["supporting"] + result["declarations"]:
            theorem(name, modules[name])
        for name in result["declarations"]:
            promised[name] = result["id"]
    if len(promised) != pins["count"]:
        raise ValueError(f"{milestone} promised theorems differ from the frozen scope")
    trusted = record["trusted"]
    if (trusted["statements"] != pins["statements"] or trusted["statements_sha256"] != pins["statements_sha256"]
            or trusted["comparator_challenge"] != pins["challenge"]
            or trusted["comparator_challenge_sha256"] != pins["challenge_sha256"]):
        raise ValueError(f"{milestone} trusted files differ from the pinned record")
    statements, challenge = read(pins["statements"]), read(pins["challenge"])
    if (hashlib.sha256(statements).hexdigest() != pins["statements_sha256"]
            or hashlib.sha256(challenge).hexdigest() != pins["challenge_sha256"]):
        raise ValueError(f"{milestone} trusted statement or challenge file changed")
    inputs = pins.get("trusted_inputs", {})
    for module, item in inputs.items():
        data = read(item["path"])
        if (item["path"] != module.replace(".", "/") + ".lean"
                or hashlib.sha256(data).hexdigest() != item["sha256"]):
            raise ValueError(f"{milestone} trusted input changed: {module}")
        if any(not name.startswith("Mathlib.") and name not in inputs for name in imported_modules(data)):
            raise ValueError(f"{milestone} trusted input imports an unpinned module: {module}")
    imports = imported_modules(statements)
    if not imports or any(not module.startswith("Mathlib.") and module not in inputs for module in imports):
        raise ValueError(f"{milestone} trusted statements import a module outside Mathlib and the pinned inputs")
    if imported_modules(challenge) != [trusted["statements_module"]]:
        raise ValueError(f"{milestone} comparator challenge imports more than the trusted statements")
    bindings = trusted["bindings"]
    bridges = [binding["theorem"] for binding in bindings]
    if len(bindings) != pins["bridges"] or len(set(bridges)) != len(bridges) or len(
            {binding["statement"] for binding in bindings}) != len(bindings):
        raise ValueError(f"{milestone} trusted bindings differ from the frozen scope")
    for binding in bindings:
        statement, name = binding["statement"], binding["theorem"]
        definition(statement, trusted["statements_module"])
        row = theorem(name, trusted["bridge_module"])
        if not (row["type"] == binding["type"] and re.fullmatch(
                r"(∀ [^,]*,\s+)?" + re.escape(statement) + r"( [A-Z])?", binding["type"])):
            raise ValueError(f"{milestone} bridge theorem does not state its trusted statement: {name}")
        if promised.get(binding["uses"]) != binding["id"] or binding["uses"] not in row["direct"]:
            raise ValueError(f"{milestone} bridge theorem does not use its promised theorem: {name}")
    config = json.loads(read(trusted["comparator_config"]))
    if (config.get("challenge_module") != trusted["comparator_challenge_module"]
            or config.get("solution_module") != trusted["bridge_module"]
            or sorted(config.get("theorem_names", [])) != sorted(bridges) or config.get("definition_names", [])
            or set(config.get("permitted_axioms", [])) != ALLOWED):
        raise ValueError(f"{milestone} comparator configuration differs from the trusted bindings")
    for name in bridges:
        if not re.search(r"^theorem " + re.escape(name.rsplit(".", 1)[1]) + r"\b.*:= sorry$", challenge.decode(),
                         re.MULTILINE):
            raise ValueError(f"{milestone} comparator challenge does not state: {name}")
    return sorted(promised), sorted(bridges)


